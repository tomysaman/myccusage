# Build data.js for index.html from the private ccusage repo's merged data.
#
# Works in Windows PowerShell 5.1 and PowerShell 7 (pwsh on macOS).
# Requires the GitHub CLI (`gh`), logged in to an account that can read the repo.
#
# Usage:
#   ./scripts/update-data.ps1                          # fetch from GitHub
#   ./scripts/update-data.ps1 -Repo owner/name         # different source repo
#   ./scripts/update-data.ps1 -Source path/to/data.js  # use a local copy instead
#
# Only per-day, per-model token/cost totals are kept (machines summed
# together). Nothing with a time of day is written: blocks, sessions,
# project names and machine tags are dropped, and generatedAt is a date.

param(
	[string]$Repo = "tomysaman/ccusage",
	[string]$Source
)

$ErrorActionPreference = "Stop"
$inv = [System.Globalization.CultureInfo]::InvariantCulture

if ($Source) {
	$text = [System.IO.File]::ReadAllText((Resolve-Path $Source))
} else {
	if (-not (Get-Command gh -ErrorAction SilentlyContinue)) {
		throw "gh (GitHub CLI) not found on PATH - install it and run 'gh auth login'"
	}
	Write-Host "Fetching data/data.js from $Repo..."
	$out = & gh api -H "Accept: application/vnd.github.raw" "repos/$Repo/contents/data/data.js"
	if ($LASTEXITCODE -ne 0) { throw "gh api failed with exit code $LASTEXITCODE" }
	$text = $out -join "`n"
}

# data.js is "window.CCUSAGE_DATA = {...};" - keep the object literal only
$text = $text.Substring($text.IndexOf("{"), $text.LastIndexOf("}") - $text.IndexOf("{") + 1)
$src = ConvertFrom-Json $text

# pwsh 7 turns ISO-looking strings into [datetime]; normalize back to strings
function Get-Day($v) {
	if ($v -is [datetime]) { return $v.ToString("yyyy-MM-dd", $inv) }
	return ([string]$v).Substring(0, 10)
}
function Int($v) { return ([long][Math]::Round([double]$v)).ToString($inv) }
function Cost($v) { return ([Math]::Round([double]$v, 4, [MidpointRounding]::AwayFromZero)).ToString($inv) }
function Str($s) { return (ConvertTo-Json -InputObject ([string]$s) -Compress) }

$models = New-Object System.Collections.Generic.List[string]
function ModelIdx($name) {
	$i = $models.IndexOf([string]$name)
	if ($i -lt 0) { $models.Add([string]$name); $i = $models.Count - 1 }
	return $i
}

# day -> model index -> [input, output, cacheWrite, cacheRead, cost]
$days = @{}

foreach ($m in $src.months) {
	foreach ($r in @($m.daily)) {
		if ($null -eq $r) { continue }
		$day = Get-Day $r.period
		if (-not $days.ContainsKey($day)) { $days[$day] = @{} }
		foreach ($b in @($r.modelBreakdowns)) {
			if ($null -eq $b) { continue }
			$mi = ModelIdx $b.modelName
			if (-not $days[$day].ContainsKey($mi)) { $days[$day][$mi] = [double[]](0, 0, 0, 0, 0) }
			$acc = $days[$day][$mi]
			$acc[0] += [double]$b.inputTokens
			$acc[1] += [double]$b.outputTokens
			$acc[2] += [double]$b.cacheCreationTokens
			$acc[3] += [double]$b.cacheReadTokens
			$acc[4] += [double]$b.cost
		}
	}
}

$dailyJson = foreach ($day in ($days.Keys | Sort-Object)) {
	$rows = foreach ($mi in ($days[$day].Keys | Sort-Object)) {
		$a = $days[$day][$mi]
		"[" + (@($mi, (Int $a[0]), (Int $a[1]), (Int $a[2]), (Int $a[3]), (Cost $a[4])) -join ",") + "]"
	}
	"[" + (Str $day) + ",[" + (@($rows) -join ",") + "]]"
}
$js = "// Generated by update-data.ps1 / update-data.sh - do not edit by hand.`n" +
	"// daily: [day, [[modelIdx, input, output, cacheWrite, cacheRead, cost], ...]]`n" +
	"window.USAGE_DATA = {`n" +
	"`"generatedAt`":" + (Str (Get-Day $src.generatedAt)) + ",`n" +
	"`"models`":[" + ((@($models) | ForEach-Object { Str $_ }) -join ",") + "],`n" +
	"`"daily`":[`n" + (@($dailyJson) -join ",`n") + "`n]`n};`n"

$outPath = Join-Path (Split-Path $PSScriptRoot -Parent) "data.js"
[System.IO.File]::WriteAllText($outPath, $js, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("Wrote {0} ({1} days, {2} models, {3:N0} KB)" -f $outPath, $days.Count, $models.Count, ((Get-Item $outPath).Length / 1KB))
