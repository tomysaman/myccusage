#!/usr/bin/env bash
# Build data.js for index.html from the private ccusage repo's merged data.
#
# macOS/Linux counterpart to update-data.ps1; writes the same data.js.
# Requires node and the GitHub CLI (`gh`), logged in to an account that can read the repo.
#
# Usage:
#   ./scripts/update-data.sh                         # fetch from GitHub
#   ./scripts/update-data.sh --repo owner/name       # different source repo
#   ./scripts/update-data.sh --source path/to/data.js  # use a local copy instead
#
# Only per-day, per-model token/cost totals are kept (machines summed
# together). Nothing with a time of day is written: blocks, sessions,
# project names and machine tags are dropped, and generatedAt is a date.

set -euo pipefail

repo="tomysaman/ccusage"
source=""
while [ $# -gt 0 ]; do
	case "$1" in
		--repo) repo="$2"; shift 2 ;;
		--source) source="$2"; shift 2 ;;
		*) echo "unknown argument: $1" >&2; exit 1 ;;
	esac
done

command -v node >/dev/null || { echo "node not found on PATH" >&2; exit 1; }

cd "$(dirname "$0")/.."
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

if [ -n "$source" ]; then
	cp "$source" "$tmp"
else
	command -v gh >/dev/null || { echo "gh (GitHub CLI) not found on PATH - install it and run 'gh auth login'" >&2; exit 1; }
	echo "Fetching data/data.js from $repo..."
	gh api -H "Accept: application/vnd.github.raw" "repos/$repo/contents/data/data.js" > "$tmp"
fi

node - "$tmp" data.js <<'EOF'
const fs = require("fs");
const [srcPath, outPath] = process.argv.slice(2);

// data.js is "window.CCUSAGE_DATA = {...};" - keep the object literal only
const text = fs.readFileSync(srcPath, "utf8");
const src = JSON.parse(text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1));

const int = v => String(Math.round(Number(v) || 0));
const cost = v => String(Math.round((Number(v) || 0) * 1e4) / 1e4);
const str = s => JSON.stringify(String(s));
// generatedAt is a UTC timestamp; take the date in local time like the daily periods
const localDay = v => {
	const d = new Date(v);
	return [d.getFullYear(), String(d.getMonth() + 1).padStart(2, "0"), String(d.getDate()).padStart(2, "0")].join("-");
};

const models = [];
const modelIdx = name => {
	let i = models.indexOf(name);
	if (i < 0) { models.push(name); i = models.length - 1; }
	return i;
};

// day -> model index -> [input, output, cacheWrite, cacheRead, cost]
const days = new Map();

for (const m of src.months || []) {
	for (const r of m.daily || []) {
		const day = String(r.period).slice(0, 10);
		if (!days.has(day)) days.set(day, new Map());
		for (const b of r.modelBreakdowns || []) {
			const mi = modelIdx(b.modelName);
			const per = days.get(day);
			if (!per.has(mi)) per.set(mi, [0, 0, 0, 0, 0]);
			const acc = per.get(mi);
			acc[0] += b.inputTokens || 0;
			acc[1] += b.outputTokens || 0;
			acc[2] += b.cacheCreationTokens || 0;
			acc[3] += b.cacheReadTokens || 0;
			acc[4] += b.cost || 0;
		}
	}
}

const dailyJson = [...days.keys()].sort().map(day => {
	const per = days.get(day);
	const rows = [...per.keys()].sort((a, b) => a - b).map(mi => {
		const a = per.get(mi);
		return "[" + [mi, int(a[0]), int(a[1]), int(a[2]), int(a[3]), cost(a[4])].join(",") + "]";
	});
	return "[" + str(day) + ",[" + rows.join(",") + "]]";
});
const js = "// Generated by update-data.ps1 / update-data.sh - do not edit by hand.\n" +
	"// daily: [day, [[modelIdx, input, output, cacheWrite, cacheRead, cost], ...]]\n" +
	"window.USAGE_DATA = {\n" +
	"\"generatedAt\":" + str(localDay(src.generatedAt)) + ",\n" +
	"\"models\":[" + models.map(str).join(",") + "],\n" +
	"\"daily\":[\n" + dailyJson.join(",\n") + "\n]\n};\n";

fs.writeFileSync(outPath, js);
console.log(`Wrote ${outPath} (${days.size} days, ${models.length} models, ${Math.round(Buffer.byteLength(js) / 1024)} KB)`);
EOF
